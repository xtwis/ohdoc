import { spawnSync } from "node:child_process"
import { existsSync, readFileSync } from "node:fs"
import { appendFile, mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"

/**
 * vitepress runtime config content.
 */
function vitepressConfigContent(file: string): string {
  return `// auto-generated by ohdoc. do not edit; modify ${file} instead.
import { buildVitepressConfig } from "@xtwis/ohdoc"
import userConfig from "../${file}"

export default buildVitepressConfig(userConfig)
`
}

/**
 * vitepress runtime theme content.
 */
function vitepressThemeContent(file: string): string {
  return `// auto-generated by ohdoc. do not edit; modify ${file} instead.
export { VITEPRESS_THEME as default } from "@xtwis/ohdoc/theme"
`
}

/**
 * ohdoc user config content.
 */
const OHDOC_CONFIG_CONTENT = `// ohdoc configuration file. see: https://x.twis.uk/en/ohdoc/guide/configuration.html
import { defineOhDocConfig } from "@xtwis/ohdoc"

export default defineOhDocConfig({
  src: "docs",
  title: "Documentation",
})
`

/**
 * cli log, colorizes title and prefixes messages.
 */
function log(title: string, ...messages: string[]): void {
  const bg = title === "error" ? "\u001B[41m" : "\u001B[46m"
  const color = "\u001B[30m"
  const reset = "\u001B[0m"
  console.log(`${bg}${color} ${title} ${reset} ${messages.join("")}`)
}

/**
 * checks whether the project is an esm package.
 */
function isESMProject(root: string): boolean {
  try {
    const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")) as { type?: string } | null
    return pkg?.type === "module"
  }
  catch {
    return false
  }
}

/**
 * resolves the file name for the module type of the project.
 */
function resolveFileName(root: string, name: string): string {
  return isESMProject(root) ? name.replace(/\.mts$/, ".ts") : name
}

/**
 * scaffolds the ohdoc workspace at root.
 */
async function runInit(root: string): Promise<number> {
  const vitepressConfigPath = path.join(root, ".vitepress", resolveFileName(root, "config.mts"))
  const ohdocConfigPath = path.join(root, resolveFileName(root, "ohdoc.config.mts"))
  const themePath = path.join(root, ".vitepress", "theme", resolveFileName(root, "index.ts"))

  try {
    await mkdir(path.join(root, ".vitepress", "theme"), { recursive: true })
    log("success", "create .vitepress at ", path.join(root, ".vitepress", "theme"))
  }
  catch (err) {
    log("error", "create .vitepress failed with ", (err as Error).message)
  }

  if (!existsSync(vitepressConfigPath)) {
    try {
      await writeFile(vitepressConfigPath, vitepressConfigContent(resolveFileName(root, "ohdoc.config.mts")), "utf8")
      log("success", `create ${resolveFileName(root, "config.mts")} at `, vitepressConfigPath)
    }
    catch (err) {
      log("error", `create ${resolveFileName(root, "config.mts")} failed with `, (err as Error).message)
    }
  }

  if (!existsSync(themePath)) {
    try {
      await writeFile(themePath, vitepressThemeContent(resolveFileName(root, "ohdoc.config.mts")), "utf8")
      log("success", "create theme at ", themePath)
    }
    catch (err) {
      log("error", "create theme failed with ", (err as Error).message)
    }
  }

  if (!existsSync(ohdocConfigPath)) {
    try {
      await writeFile(ohdocConfigPath, OHDOC_CONFIG_CONTENT, "utf8")
      log("success", `create ${resolveFileName(root, "ohdoc.config.mts")} at `, ohdocConfigPath)
    }
    catch (err) {
      log("error", `create ${resolveFileName(root, "ohdoc.config.mts")} failed with `, (err as Error).message)
    }
  }

  const gitignorePath = path.join(root, ".gitignore")
  let hasEntry = false
  if (existsSync(gitignorePath)) {
    const content = readFileSync(gitignorePath, "utf8")
    hasEntry = content.split(/\r?\n/).some(line => line.trim() === ".vitepress/" || line.trim() === ".vitepress")
  }
  if (!hasEntry) {
    try {
      await appendFile(gitignorePath, "\n# OhDoc Vitepress\n.vitepress/\n", "utf8")
      log("success", "append .vitepress/ entry to ", gitignorePath)
    }
    catch (err) {
      log("error", "append .vitepress/ entry to ", gitignorePath, " failed with ", (err as Error).message)
    }
  }

  return 0
}

/**
 * spawns vitepress and returns its exit code.
 */
function runVitepress(args: string[]): number {
  const r = spawnSync("npx", ["vitepress", ...args], { stdio: "inherit", shell: true })
  return r.status ?? 1
}

/**
 * cli entry, routes argv to init or vitepress commands.
 */
async function main(): Promise<void> {
  const command = process.argv[2]
  let code = 0
  switch (command) {
    case "init":
      code = await runInit(process.cwd())
      break
    case "dev":
      code = runVitepress(["dev"])
      break
    case "build":
      code = runVitepress(["build"])
      break
    case "preview":
      code = runVitepress(["preview"])
      break
    default:
      code = 1
  }
  if (code !== 0) {
    process.exit(code)
  }
}

main().catch((err) => {
  log("error", (err as Error).message)
  process.exit(1)
})
